// Convert trusted, installed preset equations to static functions, never runtime eval.
import {createRequire} from 'node:module';
import {writeFileSync,readFileSync} from 'node:fs';
const require=createRequire(import.meta.url);
const names=['Flexi - alien fish pond','Flexi - mindblob [shiny mix]','Geiss - Reaction Diffusion 2','Krash + Illusion - Spiral Movement','Martin - acid wiring','martin - mandelbox explorer - high speed demo version','Unchained & Rovastar - Wormhole Pillars (Hall of Shadows mix)','Flexi, martin + geiss - dedicated to the sherwin maxawow'];
const entries=names.map(name=>{
 const preset=JSON.parse(readFileSync(require.resolve(`butterchurn-presets/presets/converted/${name}.json`),'utf8'));
 const encode=value=>{
  if(Array.isArray(value))return `[${value.map(encode).join(',')}]`;
  if(value&&typeof value==='object')return `{${Object.entries(value).map(([key,v])=>key.endsWith('_eqs_str')?`${JSON.stringify(key.slice(0,-4))}:function(a){${v||''}\nreturn a;}`:`${JSON.stringify(key)}:${encode(v)}`).join(',')}}`;
  return JSON.stringify(value);
 };
 return `${JSON.stringify(name)}:${encode(preset)}`;
});
writeFileSync('apps/web/src/milkdrop/presets.js',`/* eslint-disable */\n// Generated by scripts/prepare-milkdrop.mjs from butterchurn-presets (MIT).\nexport default {${entries.join(',\n')}};\n`);
writeFileSync('apps/web/src/milkdrop/presets.d.ts','declare const presets:Record<string,object>; export default presets;\n');
writeFileSync('apps/web/src/milkdrop/names.ts',`// Actual names from butterchurn-presets; generated by scripts/prepare-milkdrop.mjs.\nexport const presetNames=${JSON.stringify(names,null,2)} as const;\n`);
